val LocalAppStrings = compositionLocalOf { FrenchStrings }

@Composable
fun resolveStrings(appLanguage: AppLanguage): Strings {
    return when (appLanguage) {
        AppLanguage.FRENCH -> FrenchStrings
        AppLanguage.ENGLISH -> EnglishStrings
        AppLanguage.SYSTEM -> {
            val systemLang = Locale.getDefault().language
            if (systemLang.startsWith("en", ignoreCase = true)) EnglishStrings else FrenchStrings
        }
    }
}

fun formatCumulativeDuration(seconds: Long): String {
    if (seconds <= 0L) return "0 s"
    val h = seconds / 3600
    val m = (seconds % 3600) / 60
    val s = seconds % 60
    return when {
        h > 0 -> "${h} h ${m} min ${s} s"
        m > 0 -> "${m} min ${s} s"
        else -> "${s} s"
    }
}

